<?php
/**
 * Tests for llms.txt source de-duplication tests (spec §7.5).
 *
 * @package X7velo
 */

namespace X7velo\Tests\Detection;

use WP_UnitTestCase;
use X7velo\Detection\Detector;

/**
 * Sources from adapters, physical files and x7velo.
 */
final class LlmsSourceTest extends WP_UnitTestCase {

	/**
	 * Setup.
	 */
	public function set_up(): void {
		parent::set_up();
		update_option( 'permalink_structure', '/%postname%/' );
	}

	/**
	 * Source IDs.
	 *
	 * @param FakeEnvironment $env     Env.
	 * @param bool            $x7velo  x7velo toggle.
	 * @return string[]
	 */
	private function ids( FakeEnvironment $env, bool $x7velo = false ): array {
		return array_column( ( new Detector( $env ) )->llms_sources( $x7velo ), 'id' );
	}

	/**
	 * AC54: each plugin source and a physical file are detected.
	 */
	public function test_sources(): void {
		$this->assertSame( array(), $this->ids( new FakeEnvironment() ) );

		SeoFixtures::load( SeoFixtures::YOAST );
		SeoFixtures::merge( 'wpseo', array( 'enable_llms_txt' => true ) );
		$this->assertSame( array( 'yoast' ), $this->ids( ( new FakeEnvironment() )->with( 'yoast' ) ) );

		SeoFixtures::load( SeoFixtures::AIOSEO );
		$data                              = json_decode( get_option( 'aioseo_options' ), true );
		$data['sitemap']['llms']['enable'] = true;
		update_option( 'aioseo_options', wp_json_encode( $data ) );
		$this->assertSame( array( 'aioseo' ), $this->ids( ( new FakeEnvironment() )->with( 'aioseo' ) ) );

		SeoFixtures::load( SeoFixtures::RANK_MATH );
		SeoFixtures::merge( 'rank_math_modules', array( 'llms-txt' ) );
		$this->assertSame( array( 'rank-math' ), $this->ids( ( new FakeEnvironment() )->with( 'rank-math' ) ) );

		$env                          = new FakeEnvironment();
		$env->files['/site/llms.txt'] = "# Hand made\n";
		$sources                      = ( new Detector( $env ) )->llms_sources();
		$this->assertSame( 'file', $sources[0]['id'] );
		$this->assertTrue( $sources[0]['served'] );
	}

	/**
	 * AC55: Rank Math module on but unregistered → not a source.
	 */
	public function test_rank_math_unregistered_not_counted(): void {
		SeoFixtures::load( SeoFixtures::RANK_MATH );
		SeoFixtures::merge( 'rank_math_modules', array( 'llms-txt' ) );
		delete_option( 'rank_math_registration_skip' );
		$this->assertSame( array(), $this->ids( ( new FakeEnvironment() )->with( 'rank-math' ) ) );
	}

	/**
	 * AC56: Yoast's own file (hash match) is one source; a foreign file makes two.
	 */
	public function test_yoast_file_with_matching_hash_is_one_source(): void {
		SeoFixtures::load( SeoFixtures::YOAST );
		SeoFixtures::merge( 'wpseo', array( 'enable_llms_txt' => true ) );
		$env                          = ( new FakeEnvironment() )->with( 'yoast' );
		$env->files['/site/llms.txt'] = "# Shop\nGenerated by Yoast SEO\n";
		update_option( 'wpseo_llms_txt_content_hash', md5( $env->files['/site/llms.txt'] ) );

		$sources = ( new Detector( $env ) )->llms_sources();
		$this->assertSame( array( 'yoast' ), array_column( $sources, 'id' ) );
		$this->assertTrue( $sources[0]['served'] );

		update_option( 'wpseo_llms_txt_content_hash', 'other' );
		$this->assertSame( array( 'yoast', 'file' ), $this->ids( $env ) );
	}

	/**
	 * AC57: Rank Math dynamic + unattributed file → two sources, the file is served.
	 */
	public function test_rank_math_plus_unattributed_file_warns_names_file(): void {
		SeoFixtures::load( SeoFixtures::RANK_MATH );
		SeoFixtures::merge( 'rank_math_modules', array( 'llms-txt' ) );
		$env                          = ( new FakeEnvironment() )->with( 'rank-math' );
		$env->files['/site/llms.txt'] = "# Mine\n";
		$sources                      = ( new Detector( $env ) )->llms_sources();
		$this->assertSame( array( 'rank-math', 'file' ), array_column( $sources, 'id' ) );
		$this->assertSame( array( false, true ), array_column( $sources, 'served' ) );

		unset( $env->files['/site/llms.txt'] );
		$this->assertTrue( ( new Detector( $env ) )->llms_sources()[0]['served'] );
	}

	/**
	 * The x7velo source counts only when alone and permalinks are readable (otherwise paused / cannot run).
	 */
	public function test_x7velo_source(): void {
		$this->assertSame( array( 'x7velo' ), $this->ids( new FakeEnvironment(), true ) );

		$env                          = new FakeEnvironment();
		$env->files['/site/llms.txt'] = 'x';
		$this->assertSame( array( 'file' ), $this->ids( $env, true ) );

		update_option( 'permalink_structure', '' );
		$this->assertSame( array(), $this->ids( new FakeEnvironment(), true ) );
	}
}
