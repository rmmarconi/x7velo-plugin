<?php
/**
 * Yoast adapter tests.
 *
 * @package X7velo
 */

namespace X7velo\Tests\Detection\Adapters;

use WP_UnitTestCase;
use X7velo\Detection\Adapters\Yoast;
use X7velo\Tests\Detection\FakeEnvironment;
use X7velo\Tests\Detection\SeoFixtures;

/**
 * Yoast SEO free, options from the captured 28.9 fixture; constant simulated.
 */
final class YoastAdapterTest extends WP_UnitTestCase {

	/**
	 * Adapter with Yoast "active".
	 *
	 * @param FakeEnvironment|null $env Env.
	 */
	private function adapter( ?FakeEnvironment $env = null ): Yoast {
		return new Yoast( $env ?? ( new FakeEnvironment() )->with( 'yoast' ) );
	}

	/**
	 * Active only with WPSEO_VERSION.
	 */
	public function test_active_by_constant(): void {
		$this->assertFalse( ( new Yoast( new FakeEnvironment() ) )->is_active() );
		$this->assertTrue( $this->adapter()->is_active() );
	}

	/**
	 * AC18: free Yoast never emits Product, schema on or off.
	 */
	public function test_free_does_not_emit_product(): void {
		SeoFixtures::load( SeoFixtures::YOAST );
		$this->assertFalse( $this->adapter()->emits_product() );
		$this->assertFalse( $this->adapter()->removes_woo_product() );

		SeoFixtures::merge( 'wpseo', array( 'enable_schema' => false ) );
		$this->assertFalse( $this->adapter()->emits_product() );
	}

	/**
	 * Organization only with company name + logo (or person), and schema on.
	 */
	public function test_organization(): void {
		SeoFixtures::load( SeoFixtures::YOAST );
		$this->assertFalse( $this->adapter()->emits_organization() );

		SeoFixtures::merge(
			'wpseo_titles',
			array(
				'company_or_person' => 'company',
				'company_name'      => 'Shop',
			)
		);
		$this->assertFalse( $this->adapter()->emits_organization(), 'Name without logo.' );

		SeoFixtures::merge( 'wpseo_titles', array( 'company_logo_id' => 5 ) );
		$this->assertTrue( $this->adapter()->emits_organization() );

		SeoFixtures::merge( 'wpseo', array( 'enable_schema' => false ) );
		$this->assertFalse( $this->adapter()->emits_organization() );
	}

	/**
	 * Sitemap on by default with products; noindex-product excludes them; off → null.
	 */
	public function test_sitemap(): void {
		SeoFixtures::load( SeoFixtures::YOAST );
		$this->assertSame(
			array(
				'path'              => '/sitemap_index.xml',
				'includes_products' => true,
			),
			$this->adapter()->sitemap()
		);

		SeoFixtures::merge( 'wpseo_titles', array( 'noindex-product' => true ) );
		$this->assertFalse( $this->adapter()->sitemap()['includes_products'] );

		SeoFixtures::merge( 'wpseo', array( 'enable_xml_sitemap' => false ) );
		$this->assertNull( $this->adapter()->sitemap() );
	}

	/**
	 * The llms.txt file: off by default; on → physical file owned iff md5 matches the stored hash.
	 */
	public function test_llms(): void {
		SeoFixtures::load( SeoFixtures::YOAST );
		$this->assertNull( $this->adapter()->llms_source() );

		SeoFixtures::merge( 'wpseo', array( 'enable_llms_txt' => true ) );
		$env                          = ( new FakeEnvironment() )->with( 'yoast' );
		$env->files['/site/llms.txt'] = "\xEF\xBB\xBF# Shop\nGenerated by Yoast SEO v28.9\n";
		$this->assertSame(
			array(
				'kind' => 'physical',
				'path' => '/site/llms.txt',
			),
			$this->adapter( $env )->llms_source()
		);

		$this->assertFalse( $this->adapter( $env )->owns_llms_file( '/site/llms.txt' ), 'No hash stored.' );
		update_option( 'wpseo_llms_txt_content_hash', md5( $env->files['/site/llms.txt'] ) );
		$this->assertTrue( $this->adapter( $env )->owns_llms_file( '/site/llms.txt' ) );
		$env->files['/site/llms.txt'] .= 'edited';
		$this->assertFalse( $this->adapter( $env )->owns_llms_file( '/site/llms.txt' ) );
	}

	/**
	 * Robots block mirrors Yoast's presenter (byte-equal to the 28.9 front-end output).
	 */
	public function test_robots_block(): void {
		SeoFixtures::load( SeoFixtures::YOAST );
		$robots = $this->adapter()->robots();
		$this->assertSame( 'append', $robots['mode'] );
		$this->assertSame(
			"# START YOAST BLOCK\n# ---------------------------\nUser-agent: *\nDisallow:\n\nSitemap: " . home_url( '/sitemap_index.xml' ) . "\n# ---------------------------\n# END YOAST BLOCK",
			$robots['content']
		);

		SeoFixtures::merge(
			'wpseo',
			array(
				'deny_search_crawling' => true,
				'deny_adsbot_crawling' => true,
				'enable_xml_sitemap'   => false,
			)
		);
		$this->assertSame(
			"# START YOAST BLOCK\n# ---------------------------\nUser-agent: *\nDisallow: /?s=\nDisallow: /page/*/?s=\nDisallow: /search/\n\nUser-agent: AdsBot\nDisallow: /\n\n# ---------------------------\n# END YOAST BLOCK",
			$this->adapter()->robots()['content']
		);
	}
}
