<?php
/**
 * AIOSEO adapter tests.
 *
 * @package X7velo
 */

namespace X7velo\Tests\Detection\Adapters;

use WP_UnitTestCase;
use X7velo\Detection\Adapters\Aioseo;
use X7velo\Tests\Detection\FakeEnvironment;
use X7velo\Tests\Detection\SeoFixtures;

/**
 * AIOSEO Lite, JSON options from the captured 5.0.5.1 fixture.
 */
final class AioseoAdapterTest extends WP_UnitTestCase {

	/**
	 * Adapter.
	 *
	 * @param FakeEnvironment|null $env Env.
	 */
	private function adapter( ?FakeEnvironment $env = null ): Aioseo {
		return new Aioseo( $env ?? ( new FakeEnvironment() )->with( 'aioseo' ) );
	}

	/**
	 * Rewrites a dotted key in a JSON option.
	 *
	 * @param string $option Option.
	 * @param string $path   Dotted path.
	 * @param mixed  $value  Value.
	 */
	private function set_json( string $option, string $path, $value ): void {
		$data = json_decode( get_option( $option ), true );
		$ref  = &$data;
		foreach ( explode( '.', $path ) as $key ) {
			$ref = &$ref[ $key ];
		}
		$ref = $value;
		update_option( $option, wp_json_encode( $data ) );
	}

	/**
	 * AC19: Lite emits no Product; Organization by default.
	 */
	public function test_lite_does_not_emit_product(): void {
		SeoFixtures::load( SeoFixtures::AIOSEO );
		$this->assertTrue( $this->adapter()->is_active() );
		$this->assertFalse( $this->adapter()->emits_product() );
		$this->assertTrue( $this->adapter()->emits_organization() );
		$this->assertFalse( ( new Aioseo( new FakeEnvironment() ) )->is_active() );
	}

	/**
	 * Sitemap at /sitemap.xml; products via all/included; dynamic noindex excludes.
	 */
	public function test_sitemap(): void {
		SeoFixtures::load( SeoFixtures::AIOSEO );
		$this->assertSame(
			array(
				'path'              => '/sitemap.xml',
				'includes_products' => true,
			),
			$this->adapter()->sitemap()
		);

		$this->set_json( 'aioseo_options', 'sitemap.general.postTypes', array( 'all' => false, 'included' => array( 'post' ) ) ); // phpcs:ignore WordPress.Arrays.ArrayDeclarationSpacing.AssociativeArrayFound
		$this->assertFalse( $this->adapter()->sitemap()['includes_products'] );

		$this->set_json( 'aioseo_options', 'sitemap.general.postTypes.included', array( 'post', 'product' ) );
		$this->assertTrue( $this->adapter()->sitemap()['includes_products'] );

		$this->set_json( 'aioseo_options_dynamic', 'searchAppearance.postTypes.product.advanced.robotsMeta.default', false );
		$this->set_json( 'aioseo_options_dynamic', 'searchAppearance.postTypes.product.advanced.robotsMeta.noindex', true );
		$this->assertFalse( $this->adapter()->sitemap()['includes_products'] );

		$this->set_json( 'aioseo_options', 'sitemap.general.enable', false );
		$this->assertNull( $this->adapter()->sitemap() );
	}

	/**
	 * The llms.txt file: physical file, owned when it carries AIOSEO's signature.
	 */
	public function test_llms(): void {
		SeoFixtures::load( SeoFixtures::AIOSEO );
		$this->assertNull( $this->adapter()->llms_source() );

		$this->set_json( 'aioseo_options', 'sitemap.llms.enable', true );
		$env = ( new FakeEnvironment() )->with( 'aioseo' );
		$this->assertSame( '/site/llms.txt', $this->adapter( $env )->llms_source()['path'] );

		$env->files['/site/llms.txt'] = "# Shop\n> Generated by All in One SEO v5.0.5.1, this is an llms.txt file\n";
		$this->assertTrue( $this->adapter( $env )->owns_llms_file( '/site/llms.txt' ) );
		$env->files['/site/llms.txt'] = "# Shop\n";
		$this->assertFalse( $this->adapter( $env )->owns_llms_file( '/site/llms.txt' ) );
	}

	/**
	 * Corrupt option JSON reads as defaults, never fatal.
	 */
	public function test_corrupt_options(): void {
		update_option( 'aioseo_options', '{not json' );
		$this->assertSame( '/sitemap.xml', $this->adapter()->sitemap()['path'] );
		$this->assertNull( $this->adapter()->llms_source() );
	}
}
