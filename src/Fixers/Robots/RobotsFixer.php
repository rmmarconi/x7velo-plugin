<?php
/**
 * Robots fixer: appends x7velo's block to the filtered robots.txt (spec §6.3, §6.4, §8.4).
 *
 * @package X7velo
 */

namespace X7velo\Fixers\Robots;

use X7velo\Audit\Checks\AiSearchCrawlers;
use X7velo\Data\AiCrawlers;
use X7velo\Detection\Detector;
use X7velo\Detection\RobotsRules;
use X7velo\Plugin;
use X7velo\Settings;

defined( 'ABSPATH' ) || exit;

/**
 * WordPress glue around RobotsBlock:
 *
 * - `robots_txt` at PHP_INT_MAX - 10 (after Yoast 99999, AIOSEO 10000, Rank Math 10) appends
 *   the block to whatever the owner's stack produced; returns its input unchanged while
 *   RobotsRules::computing_owner_rules() is true, when nothing is needed, or when the fixer
 *   can't run (search engines discouraged, subfolder install, plain permalinks);
 * - `x7velo_robots_block` gives the audit the exact block for the owner rules it computed, so
 *   CRAWL-01/02 score what crawlers get;
 * - `x7velo_fixer_status` (priority 20, after detection) adds `lines` {allow, training, sitemap}
 *   for "Show the exact lines" and, with a physical robots.txt, the copy-paste blocks.
 *
 * Never touches a physical robots.txt (the web server serves it; the filter has no effect).
 */
final class RobotsFixer {

	/**
	 * `robots_txt` priority (spec §6.3).
	 */
	public const PRIORITY = PHP_INT_MAX - 10;

	/**
	 * Hooks the fixer.
	 */
	public static function register(): void {
		add_filter( 'robots_txt', array( self::class, 'filter_robots_txt' ), self::PRIORITY, 2 );
		add_filter( 'x7velo_robots_block', array( self::class, 'filter_block' ), 10, 2 );
		add_filter( 'x7velo_fixer_status', array( self::class, 'filter_status' ), 20, 2 );
	}

	/**
	 * `robots_txt` callback.
	 *
	 * @param mixed $output Robots output so far.
	 * @param mixed $site_public Core's blog_public flag (unused; the option is read directly).
	 * @return mixed
	 */
	public static function filter_robots_txt( $output, $site_public = null ) { // phpcs:ignore Generic.CodeAnalysis.UnusedFunctionParameter.FoundAfterLastUsed -- Filter signature.
		if ( ! is_string( $output ) || RobotsRules::computing_owner_rules() || '' !== self::unavailable_reason() ) {
			return $output;
		}
		$block = self::block_for( $output, ( new Settings() )->all() );
		return '' === $block ? $output : rtrim( $output ) . "\n\n" . $block;
	}

	/**
	 * `x7velo_robots_block` callback: the block for the given owner rules and current settings.
	 *
	 * @param mixed $block       Block so far.
	 * @param mixed $owner_rules Owner rules.
	 * @return mixed
	 */
	public static function filter_block( $block, $owner_rules = '' ) {
		if ( ! is_string( $owner_rules ) || '' !== self::unavailable_reason() ) {
			return $block;
		}
		return self::block_for( $owner_rules, ( new Settings() )->all() );
	}

	/**
	 * `x7velo_fixer_status` callback: adds `lines` to the robots row, and `cannot_run` with
	 * plain permalinks (WordPress doesn't serve a virtual robots.txt without rewrite rules).
	 *
	 * @param mixed $status   Area => status row.
	 * @param mixed $settings Sanitised settings.
	 * @return mixed
	 */
	public static function filter_status( $status, $settings = array() ) {
		if ( ! is_array( $status ) || ! is_array( $status['robots'] ?? null ) ) {
			return $status;
		}
		$settings = is_array( $settings ) ? $settings : array();
		$row      = $status['robots'];

		if ( 'cannot_run' === ( $row['state'] ?? '' ) ) {
			// Physical file: copy-paste blocks generated by the same algorithm against the file.
			if ( 'physical_robots_file' === ( $row['reason'] ?? '' ) ) {
				$rules            = new RobotsRules( new Detector() );
				$row['lines']     = self::lines( $rules->owner()['text'], $settings );
				$status['robots'] = $row;
			}
			return $status;
		}

		$reason = self::unavailable_reason();
		if ( '' !== $reason ) {
			$status['robots'] = array(
				'state'  => 'cannot_run',
				'reason' => $reason,
			);
			if ( 'plain_permalinks' === $reason ) {
				$status['robots']['url'] = admin_url( 'options-permalink.php' );
			}
			return $status;
		}

		$rules            = new RobotsRules( new Detector() );
		$row['lines']     = self::lines( $rules->owner()['text'], $settings );
		$status['robots'] = $row;
		return $status;
	}

	/**
	 * Why the filter can't act ('' = it can): search engines discouraged (core already serves
	 * `Disallow: /` and we never undo it), subfolder install, plain permalinks.
	 */
	public static function unavailable_reason(): string {
		if ( '0' === (string) get_option( 'blog_public', '1' ) ) {
			return 'search_engines_discouraged';
		}
		if ( RobotsRules::is_subfolder_install() ) {
			return 'subfolder_install';
		}
		if ( '' === trim( (string) get_option( 'permalink_structure', '' ) ) ) {
			return 'plain_permalinks';
		}
		return '';
	}

	/**
	 * The block for owner rules and settings ('' = none).
	 *
	 * @param string               $owner_rules Owner rules.
	 * @param array<string, mixed> $settings    Settings.
	 */
	public static function block_for( string $owner_rules, array $settings ): string {
		if ( ! self::any_on( $settings ) ) {
			return ''; // Cheap path: no queries when every option is off.
		}
		return RobotsBlock::build( $owner_rules, $settings, AiCrawlers::agents(), self::site() )['block'];
	}

	/**
	 * The exact lines each option would add for these owner rules (preview / copy-paste):
	 * `allow` and `sitemap` as if "Let AI shopping assistants in" were on, `training` as if
	 * "Also block AI training bots" were on (plus the Google-Extended / experimental choices).
	 *
	 * @param string               $owner_rules Owner rules.
	 * @param array<string, mixed> $settings    Settings.
	 * @return array{allow: string, training: string, sitemap: string}
	 */
	public static function lines( string $owner_rules, array $settings ): array {
		$preview = array_merge(
			$settings,
			array(
				'fix_robots_search'         => true,
				'fix_robots_block_training' => true,
			)
		);
		$built   = RobotsBlock::build( $owner_rules, $preview, AiCrawlers::agents(), self::site() );
		return array(
			'allow'    => $built['allow'],
			'training' => $built['training'],
			'sitemap'  => $built['sitemap'],
		);
	}

	/**
	 * Site facts for the builder.
	 *
	 * @return array{admin_path: string, ajax_path: string, private_paths: string[], sitemap_url: string, home_host: string, sample_paths: string[], fallbacks: array<string, string>}
	 */
	public static function site(): array {
		$sitemap = ( new Detector() )->sitemap();
		return array(
			'admin_path'    => (string) wp_parse_url( admin_url(), PHP_URL_PATH ),
			'ajax_path'     => (string) wp_parse_url( admin_url( 'admin-ajax.php' ), PHP_URL_PATH ),
			'private_paths' => self::private_paths(),
			'sitemap_url'   => null === $sitemap ? '' : home_url( $sitemap['path'] ),
			'home_host'     => strtolower( (string) wp_parse_url( home_url(), PHP_URL_HOST ) ),
			'sample_paths'  => AiSearchCrawlers::sample_paths(),
			'fallbacks'     => AiSearchCrawlers::fallbacks(),
		);
	}

	/**
	 * Cart, checkout and my-account paths from their real permalinks (so `/carrinho/` works);
	 * pages that aren't set or published are skipped. Empty without WooCommerce (spec §15.3).
	 *
	 * @return string[]
	 */
	public static function private_paths(): array {
		if ( ! Plugin::is_woocommerce_active() || ! function_exists( 'wc_get_page_id' ) || ! function_exists( 'wc_get_page_permalink' ) ) {
			return array();
		}
		$paths = array();
		foreach ( array( 'cart', 'checkout', 'myaccount' ) as $page ) {
			$id = (int) wc_get_page_id( $page );
			if ( $id <= 0 || 'publish' !== get_post_status( $id ) ) {
				continue;
			}
			$path = (string) wp_parse_url( (string) wc_get_page_permalink( $page ), PHP_URL_PATH );
			if ( '' !== $path && '/' !== $path ) {
				$paths[] = $path;
			}
		}
		return array_values( array_unique( $paths ) );
	}

	/**
	 * Whether any robots option is on.
	 *
	 * @param array<string, mixed> $settings Settings.
	 */
	private static function any_on( array $settings ): bool {
		return ! empty( $settings['fix_robots_search'] )
			|| ! empty( $settings['fix_robots_block_training'] )
			|| ! empty( $settings['block_google_extended'] )
			|| ! empty( $settings['block_experimental'] );
	}
}
