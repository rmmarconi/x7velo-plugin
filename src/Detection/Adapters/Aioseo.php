<?php
/**
 * All in One SEO (Lite) adapter.
 *
 * @package X7velo
 */

namespace X7velo\Detection\Adapters;

defined( 'ABSPATH' ) || exit;

/**
 * AIOSEO Lite (verified on 5.0.5.1). Emits no Product. Options are JSON strings in
 * `aioseo_options` / `aioseo_options_dynamic`. Its robots rules are added in every context,
 * so nothing is reconstructed.
 */
final class Aioseo extends BaseAdapter {

	public const ID = 'aioseo';

	/**
	 * Text in the header of AIOSEO's generated llms.txt.
	 */
	public const LLMS_SIGNATURE = 'Generated by All in One SEO';

	/**
	 * `aioseo_posts` robots rows loaded by prime_noindex(), post ID => row (null: no row).
	 *
	 * @var array<int, array{default: bool, noindex: bool}|null>
	 */
	private array $post_robots = array();

	/**
	 * {@inheritDoc}
	 */
	public function id(): string {
		return self::ID;
	}

	/**
	 * {@inheritDoc}
	 */
	public function label(): string {
		return 'All in One SEO';
	}

	/**
	 * {@inheritDoc}
	 */
	public function is_active(): bool {
		return $this->env->defined( 'AIOSEO_VERSION' );
	}

	/**
	 * Decoded JSON option.
	 *
	 * @param string $name Option name.
	 * @return array<mixed>
	 */
	private function json_option( string $name ): array {
		$raw = $this->env->option( $name, '' );
		if ( is_array( $raw ) ) {
			return $raw;
		}
		$data = is_string( $raw ) && '' !== $raw ? json_decode( $raw, true ) : null;
		return is_array( $data ) ? $data : array();
	}

	/**
	 * Value at a dotted path of the main options.
	 *
	 * @param string $path    Dotted path, e.g. "sitemap.general.enable".
	 * @param mixed  $fallback Value when missing.
	 * @param string $option  Option name.
	 * @return mixed
	 */
	private function get( string $path, $fallback = null, string $option = 'aioseo_options' ) {
		$value = $this->json_option( $option );
		foreach ( explode( '.', $path ) as $key ) {
			if ( ! is_array( $value ) || ! array_key_exists( $key, $value ) ) {
				return $fallback;
			}
			$value = $value[ $key ];
		}
		return $value;
	}

	/**
	 * {@inheritDoc}
	 */
	public function emits_organization(): bool {
		return 'organization' === $this->get( 'searchAppearance.global.schema.siteRepresents', 'organization' );
	}

	/**
	 * {@inheritDoc}
	 */
	public function llms_source(): ?array {
		if ( true !== $this->get( 'sitemap.llms.enable', false ) ) {
			return null;
		}
		return array(
			'kind' => 'physical',
			'path' => $this->env->content_parent_path() . 'llms.txt',
		);
	}

	/**
	 * {@inheritDoc}
	 *
	 * @param string $path Absolute path of an existing llms.txt.
	 */
	public function owns_llms_file( string $path ): bool {
		$head = $this->env->read_file( $path, 4096 );
		return null !== $head && false !== strpos( $head, self::LLMS_SIGNATURE );
	}

	/**
	 * {@inheritDoc}
	 */
	public function sitemap(): ?array {
		if ( true !== $this->get( 'sitemap.general.enable', true ) ) {
			return null;
		}
		$included = (array) $this->get( 'sitemap.general.postTypes.included', array() );
		$listed   = true === $this->get( 'sitemap.general.postTypes.all', true ) || in_array( 'product', $included, true );
		$noindex  = false === $this->get( 'searchAppearance.postTypes.product.advanced.robotsMeta.default', true, 'aioseo_options_dynamic' )
			&& true === $this->get( 'searchAppearance.postTypes.product.advanced.robotsMeta.noindex', false, 'aioseo_options_dynamic' );
		return array(
			'path'              => '/sitemap.xml',
			'includes_products' => $listed && ! $noindex,
		);
	}

	/**
	 * {@inheritDoc}
	 *
	 * @param string $post_type Post type.
	 */
	public function sitemap_includes( string $post_type ): bool {
		$included = (array) $this->get( 'sitemap.general.postTypes.included', array() );
		return true === $this->get( 'sitemap.general.postTypes.all', true ) || in_array( $post_type, $included, true );
	}

	/**
	 * {@inheritDoc}
	 *
	 * Reads `aioseo_posts` rows for all posts in one prepared query (table existence checked).
	 *
	 * @param int[] $ids Post IDs.
	 */
	public function prime_noindex( array $ids ): void {
		$missing = array_values( array_diff( array_map( 'intval', $ids ), array_keys( $this->post_robots ) ) );
		if ( array() === $missing ) {
			return;
		}
		$rows = $this->env->aioseo_post_robots( $missing );
		foreach ( $missing as $id ) {
			$this->post_robots[ $id ] = $rows[ $id ] ?? null;
		}
	}

	/**
	 * Per post (`aioseo_posts.robots_default` = 0): `robots_noindex`. Otherwise the post type's
	 * robots meta when it isn't "use default settings", else the global robots meta.
	 *
	 * @param int $id Post ID.
	 */
	public function is_post_noindex( int $id ): bool {
		if ( ! array_key_exists( $id, $this->post_robots ) ) {
			$this->prime_noindex( array( $id ) );
		}
		$row = $this->post_robots[ $id ] ?? null;
		if ( is_array( $row ) && ! $row['default'] ) {
			return $row['noindex'];
		}
		$type = (string) get_post_type( $id );
		if ( '' !== $type && false === $this->get( 'searchAppearance.postTypes.' . $type . '.advanced.robotsMeta.default', true, 'aioseo_options_dynamic' ) ) {
			return true === $this->get( 'searchAppearance.postTypes.' . $type . '.advanced.robotsMeta.noindex', false, 'aioseo_options_dynamic' );
		}
		return false === $this->get( 'searchAppearance.advanced.globalRobotsMeta.default', true )
			&& true === $this->get( 'searchAppearance.advanced.globalRobotsMeta.noindex', false );
	}

	/**
	 * {@inheritDoc}
	 *
	 * @param string $area Area.
	 */
	public function settings_path( string $area ): string {
		switch ( $area ) {
			case 'sitemap':
				return 'admin.php?page=aioseo-sitemaps';
			case 'sitemap_products':
				return 'admin.php?page=aioseo-search-appearance#/content-types';
			case 'llms':
				return 'admin.php?page=aioseo-sitemaps#/llms-sitemap';
			case 'robots':
				return 'admin.php?page=aioseo-tools';
		}
		return '';
	}
}
